#!/usr/bin/env python3
"""Generate the same FITD readable-font table with Debian 10 Pillow API."""
from pathlib import Path
import sys
import math
from PIL import Image, ImageDraw, ImageFont
if len(sys.argv)!=2: raise SystemExit("Usage: gen_font_buster.py UPSTREAM_SOURCE")
target=Path(sys.argv[1])/"FitdLib"/"r36sReadableFontData.h"
# Debian ARMHF image sometimes only ships the regular DejaVu font.
candidates=[
    Path("/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed.ttf"),
    Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
    Path("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"),
]
fontpath=next((str(p) for p in candidates if p.is_file()),None)
if not fontpath:
    raise SystemExit("No DejaVu TTF installed: " + ", ".join(map(str,candidates)))
print("Lakka release font:",fontpath,flush=True)
lines=["#pragma once","#include <cstdint>",
       "// Generated by Lakka ARMHF builder; readable CP850 glyphs.",
       "struct R36SReadableGlyph { uint16_t rows[18]; uint8_t advance; };"]
for size in (12,14):
    font=ImageFont.truetype(fontpath,size)
    lines.append("static const R36SReadableGlyph g_r36sReadable{}[256] = {{".format(size))
    for v in range(256):
        c=bytes([v]).decode("cp850")
        im=Image.new("L",(16,18),0)
        if v>=32 and c.isprintable() and c!="\u00a0":
            draw=ImageDraw.Draw(im)
            # Pillow 5.x has getsize rather than getlength. Baseline may differ by 1 px.
            draw.text((0,0),c,font=font,fill=255)
            adv=max(1,min(15,math.ceil(font.getsize(c)[0])))
        else: adv=4 if v==32 else 0
        rows=[]
        for y in range(18):
            bits=0
            for x in range(16):
                if im.getpixel((x,y))>=98: bits |= 0x8000 >> x
            rows.append(bits)
        lines.append("    {{ {{ {} }}, {} }},".format(", ".join("0x{:04X}".format(x) for x in rows), adv))
    lines.append("};")
target.write_text("\n".join(lines)+"\n")
print("Generated CP850 readable font:",target)
